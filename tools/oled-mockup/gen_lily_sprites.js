#!/usr/bin/env node
// Bakes Lily's flower head (core.js flowerHead) into sprites for the firmware.
// Usage: node gen_lily_sprites.js > ../../keyboards/lily58/keymaps/crrptd/lily_sprites.h
'use strict';
const c = require('./core.js');

const HCX = 16, HCY = 60; // anchor: head centre is (hcx - 0.5, hcy)
const UNTOUCHED = 2;

const sprites = c.FLOWER_SWAYS.map(([sway, droop]) => {
  const g = c.makeScreen();
  g.buf.fill(UNTOUCHED);
  c.flowerHead(g, HCX, HCY, sway, droop);
  return g.buf;
});

// One bounding box shared by every pose, so they all use the same offsets.
let x0 = c.W, x1 = -1, y0 = c.H, y1 = -1;
for (const buf of sprites) {
  for (let y = 0; y < c.H; y++) for (let x = 0; x < c.W; x++) {
    if (buf[y * c.W + x] === UNTOUCHED) continue;
    x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y);
  }
}

const out = [];
out.push('// Generated by tools/oled-mockup/gen_lily_sprites.js, do not edit by hand.');
out.push("// Lily's flower head, one sprite per sway pose. '#' = on, 'o' = off,");
out.push("// '.' = transparent. Draw at (hcx + LILY_HEAD_DX, hcy + LILY_HEAD_DY).");
out.push('#pragma once');
out.push('');
out.push(`#define LILY_HEAD_DX (${x0 - HCX})`);
out.push(`#define LILY_HEAD_DY (${y0 - HCY})`);
out.push(`#define LILY_HEAD_W ${x1 - x0 + 1}`);
out.push(`#define LILY_HEAD_H ${y1 - y0 + 1}`);
out.push(`#define LILY_HEAD_POSES ${sprites.length}`);
out.push('');
out.push('// Poses: ' + c.FLOWER_SWAYS.map(([s, d], i) => `${i} = sway ${s}${d ? ` droop ${d}` : ''}`).join(', '));
out.push('static const char *const lily_head[LILY_HEAD_POSES][LILY_HEAD_H] = {');
for (const buf of sprites) {
  out.push('    {');
  for (let y = y0; y <= y1; y++) {
    let row = '';
    for (let x = x0; x <= x1; x++) row += ['o', '#', '.'][buf[y * c.W + x]];
    out.push(`        "${row}",`);
  }
  out.push('    },');
}
out.push('};');
console.log(out.join('\n'));
